"use client";

import { Check, Pause, Play, SpeakerHigh, SpeakerSlash, Waveform } from "@phosphor-icons/react";
import { useEffect, useId, useRef, useState } from "react";
import { cn } from "@/lib/cn";
import {
  VOICE_ENGINE_PROFILES,
  VOICE_ENGINES,
  VOICE_PROFILES,
  VOICE_SPEEDS,
  type VoiceChoice,
  type VoiceEngine,
} from "@/lib/chat/client/voice";
import type { VoiceSettings } from "@/lib/chat/client/use-voice-mode";

/**
 * The speaker button in the chat header: on/off, girl or boy voice, natural or
 * device quality, speed and hands-free mode. A small preview plays the voice
 * immediately, so the choice is something you hear rather than a label.
 *
 * Only the trigger sits in the toolbar; the panel is one tap away and sized to
 * the phone screen (right-aligned to the header, never off the edge).
 */
export function VoiceMenu({
  supported,
  settings,
  speaking,
  activeEngine,
  onChange,
  onStop,
  onSample,
}: {
  supported: boolean;
  settings: VoiceSettings;
  speaking: boolean;
  /** Which engine actually spoke last, so a fallback is explained honestly. */
  activeEngine?: VoiceEngine | null;
  onChange: (patch: Partial<VoiceSettings>) => void;
  onStop: () => void;
  onSample: (voice: VoiceChoice, speed: number, engine: VoiceEngine) => void;
}) {
  const [open, setOpen] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);
  const rootRef = useRef<HTMLDivElement>(null);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const panelRef = useRef<HTMLDivElement>(null);
  const panelId = useId();
  const profile = VOICE_PROFILES[settings.voice];
  const qualityNote = !supported
    ? "Speech isn't available in this browser. Voice input and typing still work."
    : settings.engine === "natural" && activeEngine === "device"
      ? "Natural voice couldn't be reached — using your device voice right now."
      : settings.engine === "natural"
        ? "Natural voice is generated by a neural voice service. The answer text is sent there to be spoken; Proxima doesn't store it."
        : "Device voice comes from your browser. Some phones use a network voice from the browser maker.";

  const close = (focusTrigger = true) => {
    setOpen(false);
    if (focusTrigger) triggerRef.current?.focus({ preventScroll: true });
  };

  useEffect(() => {
    if (!open) return;
    const onPointer = (event: PointerEvent) => {
      if (!rootRef.current?.contains(event.target as Node)) setOpen(false);
    };
    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        event.preventDefault();
        close();
      }
    };
    document.addEventListener("pointerdown", onPointer);
    document.addEventListener("keydown", onKey);
    panelRef.current?.querySelector<HTMLElement>("button, [role=switch]")?.focus({ preventScroll: true });
    return () => {
      document.removeEventListener("pointerdown", onPointer);
      document.removeEventListener("keydown", onKey);
    };
  }, [open]);

  const sample = (
    choice: VoiceChoice = settings.voice,
    speed: number = settings.speed,
    engine: VoiceEngine = settings.engine,
  ) => {
    if (!supported) {
      setNotice("Your browser doesn't support speech. Try Chrome, Edge or Safari.");
      return;
    }
    setNotice(null);
    onSample(choice, speed, engine);
  };

  return (
    <div ref={rootRef} className="relative">
      <button
        ref={triggerRef}
        type="button"
        onClick={() => {
          setOpen((value) => !value);
          setNotice(null);
        }}
        aria-haspopup="dialog"
        aria-expanded={open}
        aria-controls={open ? panelId : undefined}
        aria-label={
          settings.enabled
            ? `Voice mode on, ${profile.label.toLowerCase()}. Change voice settings`
            : "Turn on voice mode so Proxima reads answers aloud"
        }
        title={settings.enabled ? "Voice mode on" : "Voice mode"}
        className={cn(
          "relative inline-flex tap items-center justify-center rounded-xl px-3 transition-colors duration-200",
          "hover:bg-surface-hover hover:text-fg",
          settings.enabled ? "text-[var(--accent-text)]" : "text-muted",
        )}
      >
        {settings.enabled ? (
          <SpeakerHigh weight="fill" className="size-5" aria-hidden />
        ) : (
          <SpeakerSlash weight="bold" className="size-5" aria-hidden />
        )}
        <span className="sr-only">{settings.enabled ? "Voice mode on" : "Voice mode off"}</span>
        {settings.enabled && (
          <span aria-hidden className="absolute top-2 right-2 size-1.5 rounded-full bg-[var(--accent)]" />
        )}
      </button>

      {open && (
        <div
          ref={panelRef}
          id={panelId}
          role="dialog"
          aria-label="Voice mode"
          className="absolute top-full right-0 z-50 mt-2 max-h-[min(72vh,34rem)] w-[min(21rem,calc(100vw-1.5rem))] animate-fade-up overflow-y-auto overscroll-contain rounded-2xl border border-line bg-surface-solid p-1.5 shadow-glow-strong"
        >
          <div className="flex items-center justify-between gap-2 px-3 pt-2 pb-1">
            <p className="font-mono text-[10px] font-bold tracking-[0.22em] text-subtle uppercase">
              Voice mode
            </p>
            <Waveform
              weight="bold"
              aria-hidden
              className={cn("size-4 text-subtle", speaking && "animate-pulse text-[var(--accent-text)]")}
            />
          </div>

          <button
            type="button"
            role="switch"
            aria-checked={settings.enabled}
            disabled={!supported && !settings.enabled}
            onClick={() => {
              const next = !settings.enabled;
              onChange(next ? { enabled: true } : { enabled: false, handsFree: false });
              if (next) sample();
              else onStop();
            }}
            className={cn(
              "flex w-full items-center gap-3 rounded-xl px-3 py-2.5 text-left transition-colors duration-150",
              "hover:bg-surface-hover focus:bg-surface-hover focus:outline-none disabled:cursor-not-allowed disabled:opacity-60",
            )}
          >
            <span
              aria-hidden
              className={cn(
                "grid size-8 shrink-0 place-items-center rounded-lg border border-line",
                settings.enabled ? "bg-inverse text-on-inverse" : "bg-surface-solid text-muted",
              )}
            >
              <SpeakerHigh weight={settings.enabled ? "fill" : "bold"} className="size-4" />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-sm font-extrabold text-fg">Read replies aloud</span>
              <span className="block text-xs leading-snug text-muted">
                Every new answer is spoken as it finishes.
              </span>
            </span>
            <span
              aria-hidden
              className={cn(
                "relative h-6 w-10 shrink-0 rounded-full border border-line transition-colors duration-200",
                settings.enabled ? "bg-[var(--accent)]/70" : "bg-surface-hover",
              )}
            >
              <span
                className={cn(
                  "absolute top-0.5 left-0.5 size-4.5 rounded-full bg-surface-solid shadow transition-transform duration-200",
                  settings.enabled && "translate-x-4",
                )}
              />
            </span>
          </button>

          <div className="grid grid-cols-2 gap-1.5 px-1.5 py-1">
            {(Object.keys(VOICE_PROFILES) as VoiceChoice[]).map((choice) => {
              const item = VOICE_PROFILES[choice];
              const active = settings.voice === choice;
              return (
                <button
                  key={choice}
                  type="button"
                  aria-pressed={active}
                  onClick={() => {
                    onChange({ voice: choice });
                    sample(choice);
                  }}
                  className={cn(
                    "rounded-xl border px-3 py-2.5 text-left transition-colors duration-150",
                    "focus:outline-none focus-visible:ring-2 focus-visible:ring-[var(--accent)]",
                    active
                      ? "border-[var(--accent)]/60 bg-[var(--accent)]/10"
                      : "border-line bg-surface-solid hover:bg-surface-hover",
                  )}
                >
                  <span className="flex items-center gap-1.5 text-sm font-extrabold text-fg">
                    {item.label}
                    {active && (
                      <Check weight="bold" className="size-3.5 text-[var(--accent-text)]" aria-hidden />
                    )}
                  </span>
                  <span className="block text-[11px] leading-snug text-muted">{item.hint}</span>
                </button>
              );
            })}
          </div>

          <div className="px-3 py-1.5">
            <div className="flex items-center gap-2">
              <span className="text-xs font-bold text-muted">Quality</span>
              <div
                role="group"
                aria-label="Voice quality"
                className="ml-auto flex rounded-lg border border-line bg-surface-solid p-0.5"
              >
                {VOICE_ENGINES.map((engine) => {
                  const item = VOICE_ENGINE_PROFILES[engine];
                  return (
                    <button
                      key={engine}
                      type="button"
                      aria-pressed={settings.engine === engine}
                      onClick={() => {
                        onChange({ engine });
                        sample(settings.voice, settings.speed, engine);
                      }}
                      className={cn(
                        "min-w-16 rounded-md px-2 py-1 text-[11px] font-bold transition-colors duration-150",
                        settings.engine === engine
                          ? "bg-inverse text-on-inverse"
                          : "text-muted hover:bg-surface-hover hover:text-fg",
                      )}
                    >
                      {item.label}
                    </button>
                  );
                })}
              </div>
            </div>
            <p className="mt-1 text-right text-[11px] text-subtle">
              {VOICE_ENGINE_PROFILES[settings.engine].hint}
            </p>
          </div>

          <div className="flex items-center gap-2 px-3 py-1.5">
            <span className="text-xs font-bold text-muted">Speed</span>
            <div
              role="group"
              aria-label="Speaking speed"
              className="ml-auto flex rounded-lg border border-line bg-surface-solid p-0.5"
            >
              {VOICE_SPEEDS.map((speed) => (
                <button
                  key={speed}
                  type="button"
                  aria-pressed={settings.speed === speed}
                  onClick={() => onChange({ speed })}
                  className={cn(
                    "min-w-9 rounded-md px-2 py-1 text-[11px] font-bold transition-colors duration-150",
                    settings.speed === speed
                      ? "bg-inverse text-on-inverse"
                      : "text-muted hover:bg-surface-hover hover:text-fg",
                  )}
                >
                  {speed}×
                </button>
              ))}
            </div>
          </div>

          <button
            type="button"
            onClick={() => sample()}
            disabled={!supported}
            className="flex min-h-11 w-full items-center gap-2 rounded-xl px-3 text-left text-xs font-bold text-muted transition-colors duration-150 hover:bg-surface-hover hover:text-fg disabled:cursor-not-allowed disabled:opacity-60"
          >
            <Play weight="fill" className="size-4 text-[var(--accent-text)]" aria-hidden />
            Hear this voice
            <span className="ml-auto truncate text-[11px] font-medium text-subtle">{profile.label}</span>
          </button>

          <button
            type="button"
            role="switch"
            aria-checked={settings.handsFree}
            disabled={!settings.enabled || !supported}
            onClick={() => onChange({ handsFree: !settings.handsFree })}
            className={cn(
              "flex w-full items-center gap-3 rounded-xl px-3 py-2.5 text-left transition-colors duration-150",
              "hover:bg-surface-hover focus:bg-surface-hover focus:outline-none disabled:cursor-not-allowed disabled:opacity-60",
            )}
          >
            <span
              aria-hidden
              className={cn(
                "grid size-8 shrink-0 place-items-center rounded-lg border border-line",
                settings.handsFree ? "bg-inverse text-on-inverse" : "bg-surface-solid text-muted",
              )}
            >
              <Waveform weight={settings.handsFree ? "fill" : "bold"} className="size-4" />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-sm font-extrabold text-fg">Hands-free</span>
              <span className="block text-xs leading-snug text-muted">
                After each answer, the mic opens for your next question.
              </span>
            </span>
            <span
              aria-hidden
              className={cn(
                "relative h-6 w-10 shrink-0 rounded-full border border-line transition-colors duration-200",
                settings.handsFree ? "bg-[var(--accent)]/70" : "bg-surface-hover",
              )}
            >
              <span
                className={cn(
                  "absolute top-0.5 left-0.5 size-4.5 rounded-full bg-surface-solid shadow transition-transform duration-200",
                  settings.handsFree && "translate-x-4",
                )}
              />
            </span>
          </button>

          {speaking && (
            <button
              type="button"
              onClick={onStop}
              className="flex min-h-11 w-full items-center gap-2 rounded-xl px-3 text-left text-xs font-bold text-muted transition-colors duration-150 hover:bg-surface-hover hover:text-fg"
            >
              <Pause weight="fill" className="size-4" aria-hidden />
              Stop reading
            </button>
          )}

          {notice && <p className="px-3 py-2 text-xs font-semibold text-red-500">{notice}</p>}

          <p className="border-t border-line px-3 pt-2 pb-1.5 text-[11px] leading-snug text-subtle">
            {qualityNote}
          </p>
        </div>
      )}
    </div>
  );
}
